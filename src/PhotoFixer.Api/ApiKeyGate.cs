using System.Collections.Concurrent;
using System.Security.Cryptography;
using System.Text;

namespace PhotoFixer.Api;

/// <summary>
/// Optional API-key gate for the HOSTED variant. Off by default: the
/// self-host build runs keyless (each developer runs their own instance,
/// there is nothing to meter). The hosted variant is switched on with
/// configuration only - same code, no fork:
///
///   PhotoFixer__RequireApiKey = true
///   PhotoFixer__Keys__0 = "dev-name:<sha256-hex-of-key>"   (one per developer)
///   PhotoFixer__DailyQuota = 200    (requests per key per UTC day)
///   PhotoFixer__PerMinute = 30      (burst limit per key)
///
/// Operators store only the SHA-256 hash of each key; the key itself is
/// generated by the operator (e.g. `openssl rand -hex 24`), handed to the
/// developer once, and never stored server-side or sent over chat.
/// Quotas are in-memory: they reset on restart, which a real hosted
/// deployment should replace with a persistent store before going public.
/// </summary>
public sealed class ApiKeyGate
{
    private readonly bool _required;
    private readonly Dictionary<string, string> _keyOwners; // hash -> owner name
    private readonly int _dailyQuota;
    private readonly int _perMinute;
    private readonly ConcurrentDictionary<string, Counter> _counters = new();

    private sealed class Counter
    {
        public DateOnly Day;
        public int DayCount;
        public DateTime MinuteStart;
        public int MinuteCount;
    }

    public ApiKeyGate(IConfiguration config)
    {
        _required = config.GetValue("PhotoFixer:RequireApiKey", false);
        _dailyQuota = config.GetValue("PhotoFixer:DailyQuota", 200);
        _perMinute = config.GetValue("PhotoFixer:PerMinute", 30);
        _keyOwners = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        foreach (var entry in config.GetSection("PhotoFixer:Keys").GetChildren())
        {
            var v = entry.Value;
            if (string.IsNullOrWhiteSpace(v)) continue;
            var sep = v.IndexOf(':');
            if (sep <= 0) continue;
            _keyOwners[v[(sep + 1)..].Trim()] = v[..sep].Trim();
        }
    }

    public bool Enabled => _required;

    /// <summary>Returns null when the request may proceed, else (status, message).</summary>
    public (int Status, string Message)? Check(HttpRequest req)
    {
        if (!_required) return null;

        var key = req.Headers["X-Api-Key"].ToString();
        if (string.IsNullOrWhiteSpace(key))
            return (401, "Missing X-Api-Key header. This endpoint needs a developer API key.");

        var hash = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(key.Trim())));
        if (!_keyOwners.TryGetValue(hash, out var owner))
            return (403, "Invalid API key.");

        var now = DateTime.UtcNow;
        var today = DateOnly.FromDateTime(now);
        var c = _counters.GetOrAdd(owner, _ => new Counter());
        lock (c)
        {
            if (c.Day != today) { c.Day = today; c.DayCount = 0; }
            if ((now - c.MinuteStart) >= TimeSpan.FromMinutes(1)) { c.MinuteStart = now; c.MinuteCount = 0; }
            if (c.DayCount >= _dailyQuota)
                return (429, $"Daily quota of {_dailyQuota} requests reached for this key; resets at UTC midnight.");
            if (c.MinuteCount >= _perMinute)
                return (429, "Rate limit: too many requests this minute. Slow down and retry.");
            c.DayCount++;
            c.MinuteCount++;
        }
        return null;
    }
}
